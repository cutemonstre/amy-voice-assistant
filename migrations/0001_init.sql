CREATE TABLE sessions (
  id          TEXT PRIMARY KEY,              -- UUID generated by the client
  title       TEXT,                          -- first user message, trimmed to 60 chars
  practice    TEXT NOT NULL DEFAULT 'off',   -- practice language when last used: 'off' | 'zh'
  created_at  INTEGER NOT NULL,              -- ms since epoch
  updated_at  INTEGER NOT NULL
);
CREATE INDEX sessions_updated ON sessions(updated_at DESC);

CREATE TABLE messages (
  id             INTEGER PRIMARY KEY AUTOINCREMENT,
  session_id     TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
  role           TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
  content        TEXT NOT NULL,              -- assistant text keeps [tags] and {{notes}}
  language       TEXT,                       -- user: language Scribe detected (e.g. 'eng', 'cmn')
  interrupted    INTEGER NOT NULL DEFAULT 0, -- assistant: cut off by barge-in
  tts_model      TEXT,                       -- assistant: eleven_v4 | eleven_v4_turbo | NULL (text-only)
  stt_ms         INTEGER,                    -- assistant row carries the turn's server timings
  llm_first_ms   INTEGER,
  tts_first_ms   INTEGER,
  created_at     INTEGER NOT NULL
);
CREATE INDEX messages_session ON messages(session_id, id);
